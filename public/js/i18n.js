let lang = 'en';
try { lang = localStorage.getItem('df_lang') || 'en'; } catch { /* storage unavailable */ }

export function t(key, params = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = params[k];
    if (typeof v === 'string' && v.startsWith('@')) return t(v.slice(1));
    return v ?? '';
  });
}
export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('df_lang', l); } catch { /* storage unavailable */ }
  document.documentElement.lang = l === 'mm' ? 'my' : 'en';
}
